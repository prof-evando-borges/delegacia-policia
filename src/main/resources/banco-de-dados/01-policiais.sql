CREATE TABLE TB_PLC_ENDERECO (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    RUA          VARCHAR2(150) NOT NULL,
    NUMERO       NUMBER(19) NOT NULL,
    CEP          VARCHAR2(8) NOT NULL,
    COMPLEMENTO  VARCHAR2(100),
    CONSTRAINT PK_PLC_ENDERECO PRIMARY KEY (ID),
    CONSTRAINT CK_PLC_ENDERECO_NUMERO CHECK (NUMERO > 0)
);

COMMENT ON TABLE TB_PLC_ENDERECO IS 'Enderecos das delegacias';

CREATE TABLE TB_PLC_DELEGACIA (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NOME         VARCHAR2(120) NOT NULL,
    ID_ENDERECO  NUMBER(19) NOT NULL,
    CONSTRAINT PK_PLC_DELEGACIA PRIMARY KEY (ID),
    CONSTRAINT UK_PLC_DELEGACIA_ID_ENDERECO UNIQUE (ID_ENDERECO),
    CONSTRAINT FK_PLC_DELEGACIA_ENDERECO FOREIGN KEY (ID_ENDERECO)
        REFERENCES TB_PLC_ENDERECO (ID)
);

COMMENT ON TABLE TB_PLC_DELEGACIA IS 'Delegacias de policia';

CREATE TABLE TB_PLC_POLICIAL (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NOME           VARCHAR2(120) NOT NULL,
    CPF            VARCHAR2(11) NOT NULL,
    MATRICULA      VARCHAR2(20) NOT NULL,
    CARGO          VARCHAR2(60) NOT NULL,
    ID_DELEGACIA   NUMBER(19) NOT NULL,
    CONSTRAINT PK_PLC_POLICIAL PRIMARY KEY (ID),
    CONSTRAINT UK_PLC_POLICIAL_CPF UNIQUE (CPF),
    CONSTRAINT UK_PLC_POLICIAL_MATRICULA UNIQUE (MATRICULA),
    CONSTRAINT FK_PLC_POLICIAL_DELEGACIA FOREIGN KEY (ID_DELEGACIA)
        REFERENCES TB_PLC_DELEGACIA (ID)
);

COMMENT ON TABLE TB_PLC_POLICIAL IS 'Policiais vinculados as delegacias';
