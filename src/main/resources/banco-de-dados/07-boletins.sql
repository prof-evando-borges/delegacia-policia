CREATE TABLE TB_BOL_TIPO_OCORRENCIA (
    ID         VARCHAR2(36)  NOT NULL,
    NOME       VARCHAR2(80)  NOT NULL,
    DESCRICAO  VARCHAR2(200),
    CONSTRAINT PK_BOL_TIPO_OCORRENCIA PRIMARY KEY (ID),
    CONSTRAINT UK_BOL_TIPO_OCORRENCIA_NOME UNIQUE (NOME)
);

CREATE TABLE TB_BOL_REGISTRO_BO (
    ID                 VARCHAR2(36)  NOT NULL,
    ID_TIPO_OCORRENCIA VARCHAR2(36)  NOT NULL,
    ID_POLICIAL        VARCHAR2(36)  NOT NULL,
    ID_CRIMINOSO       VARCHAR2(36),
    ID_SOLICITANTE     VARCHAR2(36),
    NUMERO_BO          VARCHAR2(20)  NOT NULL,
    DESCRICAO          VARCHAR2(500) NOT NULL,
    LOCAL_OCORRENCIA   VARCHAR2(200) NOT NULL,
    DATA_OCORRENCIA    DATE          NOT NULL,
    CONSTRAINT PK_BOL_REGISTRO_BO PRIMARY KEY (ID),
    CONSTRAINT FK_BOL_REGISTRO_BO_TIPO FOREIGN KEY (ID_TIPO_OCORRENCIA) REFERENCES TB_BOL_TIPO_OCORRENCIA (ID),
    CONSTRAINT FK_BOL_REGISTRO_BO_POLICIAL FOREIGN KEY (ID_POLICIAL) REFERENCES TB_PLC_POLICIAL (ID),
    CONSTRAINT FK_BOL_REGISTRO_BO_CRIMINOSO FOREIGN KEY (ID_CRIMINOSO) REFERENCES TB_FIC_CRIMINAL (ID),
    CONSTRAINT FK_BOL_REGISTRO_BO_SOLICIT FOREIGN KEY (ID_SOLICITANTE) REFERENCES TB_CHM_SOLICITANTE (ID),
    CONSTRAINT UK_BOL_REGISTRO_BO_NUMERO UNIQUE (NUMERO_BO)
);

COMMENT ON TABLE  TB_BOL_TIPO_OCORRENCIA IS 'Categorias de ocorrencia (Furto, Roubo, etc.)';
COMMENT ON TABLE  TB_BOL_REGISTRO_BO IS 'Boletins de ocorrencia registrados';
COMMENT ON COLUMN TB_BOL_REGISTRO_BO.NUMERO_BO IS 'Numero do boletim de ocorrencia';
COMMENT ON COLUMN TB_BOL_REGISTRO_BO.DATA_OCORRENCIA IS 'Data em que a ocorrencia aconteceu';
COMMENT ON COLUMN TB_BOL_REGISTRO_BO.ID_POLICIAL IS 'Policial atendente (modulo 01)';
COMMENT ON COLUMN TB_BOL_REGISTRO_BO.ID_CRIMINOSO IS 'Infrator, quando identificado (modulo 02)';
COMMENT ON COLUMN TB_BOL_REGISTRO_BO.ID_SOLICITANTE IS 'Vitima / solicitante, quando identificado (modulo 05)';

