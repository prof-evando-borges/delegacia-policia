-- Pode referenciar os modulos 01 a 08.
-- A pessoa presa e o cadastro TB_FIC_CRIMINAL (modulo 02, dono dos dados
-- de pessoa); o policial e TB_PLC_POLICIAL (modulo 01).
-- Os IDs VARCHAR2(36) recebem o UUID gerado pela aplicacao.
-- =====================================================================

-- TABELA CELA
CREATE TABLE TB_PRS_CELA (
    ID        VARCHAR2(36) NOT NULL,
    PAVILHAO  VARCHAR2(10) NOT NULL,
    BLOCO     VARCHAR2(10) NOT NULL,
    NUMERO    VARCHAR2(10) NOT NULL,
    CONSTRAINT PK_PRS_CELA PRIMARY KEY (ID),
    CONSTRAINT UK_PRS_CELA_LOCAL UNIQUE (PAVILHAO, BLOCO, NUMERO)
);

-- TABELA PRISAO
CREATE TABLE TB_PRS_PRISAO (
    ID           VARCHAR2(36)  NOT NULL,
    STATUS       VARCHAR2(20)  NOT NULL,
    ID_CRIMINAL  VARCHAR2(36)  NOT NULL,
    DATA_PRISAO  TIMESTAMP     NOT NULL,
    TIPO         VARCHAR2(20)  NOT NULL,
    MOTIVO       VARCHAR2(200) NOT NULL,
    ID_POLICIAL  VARCHAR2(36)  NOT NULL,
    ID_CELA      VARCHAR2(36)  NOT NULL,
    PESO         NUMBER(5,2),
    ALTURA       NUMBER(3,2),
    REINCIDENTE  NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PRS_PRISAO PRIMARY KEY (ID),
    CONSTRAINT FK_PRS_PRISAO_CRIMINAL FOREIGN KEY (ID_CRIMINAL) REFERENCES TB_FIC_CRIMINAL (ID),
    CONSTRAINT FK_PRS_PRISAO_POLICIAL FOREIGN KEY (ID_POLICIAL) REFERENCES TB_PLC_POLICIAL (ID),
    CONSTRAINT FK_PRS_PRISAO_CELA FOREIGN KEY (ID_CELA) REFERENCES TB_PRS_CELA (ID),
    CONSTRAINT CK_PRS_PRISAO_STATUS CHECK (STATUS IN ('EM_ANDAMENTO', 'CONCLUIDA', 'REVOGADA')),
    CONSTRAINT CK_PRS_PRISAO_TIPO CHECK (TIPO IN ('FLAGRANTE', 'PREVENTIVA', 'TEMPORARIA', 'MANDADO_JUDICIAL')),
    CONSTRAINT CK_PRS_PRISAO_REINCIDENTE CHECK (REINCIDENTE IN (0, 1))
);

-- Comentarios
COMMENT ON TABLE TB_PRS_PRISAO IS 'Registro de cada prisao: quem foi preso, por qual policial e em qual cela';
COMMENT ON COLUMN TB_PRS_PRISAO.ID IS 'Identificador do registro de prisao';
COMMENT ON COLUMN TB_PRS_PRISAO.STATUS IS 'Situacao da prisao: EM_ANDAMENTO, CONCLUIDA ou REVOGADA';
COMMENT ON COLUMN TB_PRS_PRISAO.ID_CRIMINAL IS 'Pessoa presa (TB_FIC_CRIMINAL, modulo 02)';
COMMENT ON COLUMN TB_PRS_PRISAO.DATA_PRISAO IS 'Data e hora em que o preso entrou na prisao';
COMMENT ON COLUMN TB_PRS_PRISAO.TIPO IS 'FLAGRANTE, PREVENTIVA, TEMPORARIA ou MANDADO_JUDICIAL';
COMMENT ON COLUMN TB_PRS_PRISAO.MOTIVO IS 'Descricao breve do motivo da prisao';
COMMENT ON COLUMN TB_PRS_PRISAO.ID_POLICIAL IS 'Policial que realizou a prisao (TB_PLC_POLICIAL, modulo 01)';
COMMENT ON COLUMN TB_PRS_PRISAO.ID_CELA IS 'Cela em que o preso esta';
COMMENT ON COLUMN TB_PRS_PRISAO.PESO IS 'Peso do preso no ingresso na prisao';
COMMENT ON COLUMN TB_PRS_PRISAO.ALTURA IS 'Altura do preso no ingresso na prisao';
COMMENT ON COLUMN TB_PRS_PRISAO.REINCIDENTE IS 'Se ja existe passagem anterior: 1 = SIM e 0 = NAO';

COMMENT ON TABLE TB_PRS_CELA IS 'Celas da prisao';
COMMENT ON COLUMN TB_PRS_CELA.PAVILHAO IS 'Numero do pavilhao';
COMMENT ON COLUMN TB_PRS_CELA.BLOCO IS 'Numero do bloco';
COMMENT ON COLUMN TB_PRS_CELA.NUMERO IS 'Numero da cela';
