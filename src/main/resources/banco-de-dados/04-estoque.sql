CREATE TABLE TB_EST_CATEGORIA (
    ID         VARCHAR2(36) NOT NULL,
    NOME       VARCHAR2(50) NOT NULL,
    DESCRICAO  VARCHAR2(200),
    CONSTRAINT PK_EST_CATEGORIA PRIMARY KEY (ID),
    CONSTRAINT UK_EST_CATEGORIA_NOME UNIQUE (NOME)
);

CREATE TABLE TB_EST_ITEM (
    ID              VARCHAR2(36) NOT NULL,
    ID_CATEGORIA    VARCHAR2(36) NOT NULL,
    CODIGO          VARCHAR2(30) NOT NULL,
    NOME            VARCHAR2(100) NOT NULL,
    DESCRICAO       CLOB,
    LOCALIZACAO     VARCHAR2(100),
    QUANTIDADE      NUMBER(10) DEFAULT 0 NOT NULL,
    VALOR_UNITARIO  NUMBER(15,2) DEFAULT 0 NOT NULL,
    ATIVO           NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_EST_ITEM PRIMARY KEY (ID),
    CONSTRAINT FK_EST_ITEM_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES TB_EST_CATEGORIA (ID),
    CONSTRAINT UK_EST_ITEM_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_EST_ITEM_QUANTIDADE CHECK (QUANTIDADE >= 0),
    CONSTRAINT CK_EST_ITEM_VALOR_UNITARIO CHECK (VALOR_UNITARIO >= 0),
    CONSTRAINT CK_EST_ITEM_ATIVO CHECK (ATIVO IN (0, 1))
);
