CREATE TABLE TB_EST_CATEGORIA (
    ID         VARCHAR2(36) NOT NULL,
    NOME       VARCHAR2(50) NOT NULL,
    DESCRICAO  VARCHAR2(200),
    CONSTRAINT PK_EST_CATEGORIA PRIMARY KEY (ID),
    CONSTRAINT UK_EST_CATEGORIA_NOME UNIQUE (NOME)
);

CREATE TABLE TB_EST_ITEM (
    ID              VARCHAR2(36) NOT NULL,
    ID_CATEGORIA    VARCHAR2(36) NOT NULL,
    CODIGO          VARCHAR2(30) NOT NULL,
    NOME            VARCHAR2(100) NOT NULL,
    DESCRICAO       CLOB,
    LOCALIZACAO     VARCHAR2(100),
    QUANTIDADE      NUMBER(10) DEFAULT 0 NOT NULL,
    VALOR_UNITARIO  NUMBER(15,2) DEFAULT 0 NOT NULL,
    ATIVO           NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_EST_ITEM PRIMARY KEY (ID),
    CONSTRAINT FK_EST_ITEM_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES TB_EST_CATEGORIA (ID),
    CONSTRAINT UK_EST_ITEM_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_EST_ITEM_QUANTIDADE CHECK (QUANTIDADE >= 0),
    CONSTRAINT CK_EST_ITEM_VALOR_UNITARIO CHECK (VALOR_UNITARIO >= 0),
    CONSTRAINT CK_EST_ITEM_ATIVO CHECK (ATIVO IN (0, 1))
);

CREATE TABLE TB_EST_MOVIMENTACAO (
    ID                 VARCHAR2(36) NOT NULL,
    ID_ITEM            VARCHAR2(36) NOT NULL,
    ID_POLICIAL        VARCHAR2(36) NOT NULL,
    TIPO               VARCHAR2(10) NOT NULL,
    QUANTIDADE         NUMBER(10) NOT NULL,
    DATA_MOVIMENTACAO  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    OBSERVACAO         VARCHAR2(255),
    CONSTRAINT PK_EST_MOVIMENTACAO PRIMARY KEY (ID),
    CONSTRAINT FK_EST_MOVIMENTACAO_ITEM FOREIGN KEY (ID_ITEM) REFERENCES TB_EST_ITEM (ID),
    CONSTRAINT FK_EST_MOVIMENTACAO_POLICIAL FOREIGN KEY (ID_POLICIAL) REFERENCES TB_PLC_POLICIAL (ID),
    CONSTRAINT CK_EST_MOVIMENTACAO_TIPO CHECK (TIPO IN ('ENTRADA', 'SAIDA')),
    CONSTRAINT CK_EST_MOVIMENTACAO_QUANTIDADE CHECK (QUANTIDADE > 0)
);

COMMENT ON TABLE TB_EST_CATEGORIA IS 'Categorias dos itens do estoque da delegacia';
COMMENT ON COLUMN TB_EST_CATEGORIA.ID IS 'Identificador unico da categoria (UUID)';
COMMENT ON COLUMN TB_EST_CATEGORIA.NOME IS 'Nome da categoria';
COMMENT ON COLUMN TB_EST_CATEGORIA.DESCRICAO IS 'Descricao resumida da categoria';

COMMENT ON TABLE TB_EST_ITEM IS 'Itens armazenados no estoque da delegacia';
COMMENT ON COLUMN TB_EST_ITEM.ID IS 'Identificador unico do item (UUID)';
COMMENT ON COLUMN TB_EST_ITEM.ID_CATEGORIA IS 'Categoria do item (TB_EST_CATEGORIA)';
COMMENT ON COLUMN TB_EST_ITEM.CODIGO IS 'Codigo interno do item';
COMMENT ON COLUMN TB_EST_ITEM.NOME IS 'Nome do item';
COMMENT ON COLUMN TB_EST_ITEM.DESCRICAO IS 'Descricao detalhada do item';
COMMENT ON COLUMN TB_EST_ITEM.LOCALIZACAO IS 'Local onde o item fica guardado';
COMMENT ON COLUMN TB_EST_ITEM.QUANTIDADE IS 'Quantidade atual em estoque';
COMMENT ON COLUMN TB_EST_ITEM.VALOR_UNITARIO IS 'Valor unitario do item em reais';
COMMENT ON COLUMN TB_EST_ITEM.ATIVO IS 'Indica se o item esta ativo (1) ou inativo (0)';

COMMENT ON TABLE TB_EST_MOVIMENTACAO IS 'Entradas e saidas dos itens do estoque';
COMMENT ON COLUMN TB_EST_MOVIMENTACAO.ID IS 'Identificador unico da movimentacao (UUID)';
COMMENT ON COLUMN TB_EST_MOVIMENTACAO.ID_ITEM IS 'Item movimentado (TB_EST_ITEM)';
COMMENT ON COLUMN TB_EST_MOVIMENTACAO.ID_POLICIAL IS 'Policial responsavel (TB_PLC_POLICIAL)';
COMMENT ON COLUMN TB_EST_MOVIMENTACAO.TIPO IS 'Tipo da movimentacao: ENTRADA ou SAIDA';
COMMENT ON COLUMN TB_EST_MOVIMENTACAO.QUANTIDADE IS 'Quantidade movimentada';
COMMENT ON COLUMN TB_EST_MOVIMENTACAO.DATA_MOVIMENTACAO IS 'Data e hora da movimentacao';
COMMENT ON COLUMN TB_EST_MOVIMENTACAO.OBSERVACAO IS 'Observacao opcional sobre a movimentacao';

