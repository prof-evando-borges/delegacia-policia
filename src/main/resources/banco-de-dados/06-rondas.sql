-- Modulo: Registro de Ronda (grupo 2) | Prefixo: TB_RND_ | Ordem: 06
-- Pode referenciar os modulos 01 a 05. Usa TB_PLC_POLICIAL (modulo 01).

-- Viatura: tabela propria do modulo
CREATE TABLE TB_RND_VIATURA (
    ID       NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PREFIXO  VARCHAR2(10) NOT NULL,
    PLACA    VARCHAR2(10) NOT NULL,
    MODELO   VARCHAR2(50),
    STATUS   VARCHAR2(20) DEFAULT 'DISPONIVEL' NOT NULL,
    CONSTRAINT PK_RND_VIATURA PRIMARY KEY (ID),
    CONSTRAINT UK_RND_VIATURA_PREFIXO UNIQUE (PREFIXO),
    CONSTRAINT UK_RND_VIATURA_PLACA UNIQUE (PLACA),
    CONSTRAINT CK_RND_VIATURA_STATUS CHECK (STATUS IN ('DISPONIVEL', 'EM_RONDA', 'MANUTENCAO'))
);

COMMENT ON TABLE TB_RND_VIATURA IS 'Viaturas usadas nas rondas';
COMMENT ON COLUMN TB_RND_VIATURA.PREFIXO IS 'Numero de identificacao da viatura na corporacao';
COMMENT ON COLUMN TB_RND_VIATURA.STATUS IS 'DISPONIVEL, EM_RONDA ou MANUTENCAO';

-- Ronda: os policiais e as viaturas ficam nas tabelas de ligacao abaixo
CREATE TABLE TB_RND_RONDA (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    DATA_INICIO  DATE NOT NULL,
    DATA_FIM     DATE,
    HORA_INICIO  VARCHAR2(5),
    HORA_FIM     VARCHAR2(5),
    ID_SETOR     NUMBER(19) NOT NULL,
    OBSERVACOES  VARCHAR2(4000),
    CONSTRAINT PK_RND_RONDA PRIMARY KEY (ID),
    CONSTRAINT CK_RND_RONDA_DATA_FIM CHECK (DATA_FIM IS NULL OR DATA_FIM >= DATA_INICIO)
);

COMMENT ON TABLE TB_RND_RONDA IS 'Rondas realizadas pela delegacia';
COMMENT ON COLUMN TB_RND_RONDA.ID_SETOR IS 'Setor patrulhado na ronda';

-- Ligacao muitos-para-muitos: uma ronda usa varias viaturas e uma viatura entra em varias rondas
CREATE TABLE TB_RND_RONDA_VIATURA (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_RONDA    NUMBER(19) NOT NULL,
    ID_VIATURA  NUMBER(19) NOT NULL,
    CONSTRAINT PK_RND_RONDA_VIATURA PRIMARY KEY (ID),
    CONSTRAINT UK_RND_RONDA_VIATURA_PAR UNIQUE (ID_RONDA, ID_VIATURA),
    CONSTRAINT FK_RND_RONDA_VIATURA_RONDA FOREIGN KEY (ID_RONDA)
        REFERENCES TB_RND_RONDA (ID),
    CONSTRAINT FK_RND_RONDA_VIATURA_VIATURA FOREIGN KEY (ID_VIATURA)
        REFERENCES TB_RND_VIATURA (ID)
);

COMMENT ON TABLE TB_RND_RONDA_VIATURA IS 'Viaturas que participaram de cada ronda';

-- Ligacao ronda-policial: o policial e do modulo 01 (TB_PLC_POLICIAL)
CREATE TABLE TB_RND_RONDA_POLICIAL (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_RONDA     NUMBER(19) NOT NULL,
    ID_POLICIAL  NUMBER(19) NOT NULL,
    CONSTRAINT PK_RND_RONDA_POLICIAL PRIMARY KEY (ID),
    CONSTRAINT UK_RND_RONDA_POLICIAL_PAR UNIQUE (ID_RONDA, ID_POLICIAL),
    CONSTRAINT FK_RND_RONDA_POLICIAL_RONDA FOREIGN KEY (ID_RONDA)
        REFERENCES TB_RND_RONDA (ID),
    CONSTRAINT FK_RND_RONDA_POLICIAL_POLICIAL FOREIGN KEY (ID_POLICIAL)
        REFERENCES TB_PLC_POLICIAL (ID)
);

COMMENT ON TABLE TB_RND_RONDA_POLICIAL IS 'Policiais que participaram de cada ronda';