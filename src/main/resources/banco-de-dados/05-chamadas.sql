CREATE TABLE TB_CHM_ATENDENTE (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_POLICIAL  NUMBER(19) NOT NULL,
    MATRICULA    VARCHAR2(20) NOT NULL,
    TURNO        VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_CHM_ATENDENTE PRIMARY KEY (ID),
    CONSTRAINT UK_CHM_ATENDENTE_MATRICULA UNIQUE (MATRICULA),
    CONSTRAINT FK_CHM_ATENDENTE_POLICIAL FOREIGN KEY (ID_POLICIAL)
        REFERENCES TB_PLC_POLICIAL (ID)
);

COMMENT ON TABLE TB_CHM_ATENDENTE IS 'Policiais que atendem as chamadas';

CREATE TABLE TB_CHM_UNIDADE_RESPONSAVEL (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    UNIDADE          VARCHAR2(100) NOT NULL,
    DESCRICAO        VARCHAR2(255),
    TELEFONE         VARCHAR2(20) NOT NULL,
    DISPONIBILIDADE  VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_CHM_UNIDADE_RESPONSAVEL PRIMARY KEY (ID),
    CONSTRAINT CK_CHM_UNIDADE_DISPONIB CHECK (DISPONIBILIDADE IN ('DISPONIVEL', 'OCUPADA', 'INDISPONIVEL'))
);

COMMENT ON TABLE TB_CHM_UNIDADE_RESPONSAVEL IS 'Unidades que podem ser enviadas para atender as chamadas';

CREATE TABLE TB_CHM_CHAMADA (
    ID                      NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PROTOCOLO               VARCHAR2(30) NOT NULL,
    NATUREZA                VARCHAR2(60) NOT NULL,
    ID_SOLICITANTE          NUMBER(19) NOT NULL,
    ID_ATENDENTE            NUMBER(19) NOT NULL,
    DESCRICAO               VARCHAR2(500) NOT NULL,
    ENDERECO                VARCHAR2(200) NOT NULL,
    STATUS                  VARCHAR2(20) NOT NULL,
    DATA_HORA               TIMESTAMP NOT NULL,
    DESFECHO                VARCHAR2(500),
    ID_UNIDADE_RESPONSAVEL  NUMBER(19),
    CONSTRAINT PK_CHM_CHAMADA PRIMARY KEY (ID),
    CONSTRAINT UK_CHM_CHAMADA_PROTOCOLO UNIQUE (PROTOCOLO),
    CONSTRAINT FK_CHM_CHAMADA_ATENDENTE FOREIGN KEY (ID_ATENDENTE)
        REFERENCES TB_CHM_ATENDENTE (ID),
    CONSTRAINT FK_CHM_CHAMADA_UNIDADE FOREIGN KEY (ID_UNIDADE_RESPONSAVEL)
        REFERENCES TB_CHM_UNIDADE_RESPONSAVEL (ID),
    CONSTRAINT CK_CHM_CHAMADA_STATUS CHECK (STATUS IN ('ABERTA', 'ENCERRADA'))
);

COMMENT ON TABLE TB_CHM_CHAMADA IS 'Chamadas recebidas pela central da delegacia';
