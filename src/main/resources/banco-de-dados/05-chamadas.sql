CREATE TABLE TB_CHM_SOLICITANTE (
    ID VARCHAR2(36) GENERATED BY DEFAULT AS UUID NOT NULL,
    NOME VARCHAR2(150) NOT NULL,
    TELEFONE VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_CHM_SOLICITANTE PRIMARY KEY (ID)
);

CREATE TABLE TB_CHM_UNIDADE_RESPONSAVEL (
    ID VARCHAR2(36) GENERATED BY DEFAULT AS UUID NOT NULL,
    UNIDADE VARCHAR2(100) NOT NULL,
    DESCRICAO VARCHAR2(500),
    TELEFONE VARCHAR2(20),
    DISPONIBILIDADE VARCHAR2(20) DEFAULT 'DISPONIVEL' NOT NULL,
    CONSTRAINT PK_CHM_UNIDADE_RESP PRIMARY KEY (ID),
    CONSTRAINT CK_CHM_UNID_DISP CHECK (
        DISPONIBILIDADE IN ('DISPONIVEL', 'INDISPONIVEL', 'EM_ATENDIMENTO')
    )
);

CREATE TABLE TB_CHM_ATENDENTE (
    ID VARCHAR2(36) GENERATED BY DEFAULT AS UUID NOT NULL,
    ID_POLICIAL NUMBER(19) NOT NULL,
    MATRICULA VARCHAR2(20) NOT NULL,
    TURNO VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_CHM_ATENDENTE PRIMARY KEY (ID),
    CONSTRAINT UK_CHM_ATENDENTE_MATRICULA UNIQUE (MATRICULA),
    CONSTRAINT UK_CHM_ATENDENTE_ID_POLICIAL UNIQUE (ID_POLICIAL),
    CONSTRAINT FK_CHM_ATENDENTE_POLICIAL FOREIGN KEY (ID_POLICIAL)
        REFERENCES TB_PLC_POLICIAL (ID)
);

CREATE TABLE TB_CHM_CHAMADA (
    ID VARCHAR2(36) GENERATED BY DEFAULT AS UUID NOT NULL,
    PROTOCOLO VARCHAR2(36) NOT NULL,
    NATUREZA VARCHAR2(100) NOT NULL,
    ID_SOLICITANTE VARCHAR2(36) NOT NULL,
    ID_ATENDENTE VARCHAR2(36),
    ID_UNIDADE_RESPONSAVEL VARCHAR2(36),
    DESCRICAO CLOB NOT NULL,
    ENDERECO VARCHAR2(255) NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'ABERTA' NOT NULL,
    DATA_HORA TIMESTAMP NOT NULL,
    DESFECHO CLOB,
    CONSTRAINT PK_CHM_CHAMADA PRIMARY KEY (ID),
    CONSTRAINT UK_CHM_CHAMADA_PROTOCOLO UNIQUE (PROTOCOLO),
    CONSTRAINT FK_CHM_CHAMADA_SOLIC FOREIGN KEY (ID_SOLICITANTE)
        REFERENCES TB_CHM_SOLICITANTE (ID),
    CONSTRAINT FK_CHM_CHAMADA_ATEND FOREIGN KEY (ID_ATENDENTE)
        REFERENCES TB_CHM_ATENDENTE (ID),
    CONSTRAINT FK_CHM_CHAMADA_UNID FOREIGN KEY (ID_UNIDADE_RESPONSAVEL)
        REFERENCES TB_CHM_UNIDADE_RESPONSAVEL (ID),
    CONSTRAINT CK_CHM_CHAMADA_STATUS CHECK (
        STATUS IN ('ABERTA', 'EM_ATENDIMENTO', 'ENCERRADA', 'CANCELADA')
    )
);

COMMENT ON TABLE TB_CHM_SOLICITANTE IS 'Pessoas que acionam a delegacia por chamada';
COMMENT ON TABLE TB_CHM_UNIDADE_RESPONSAVEL IS 'Unidades que atendem as chamadas';
COMMENT ON TABLE TB_CHM_ATENDENTE IS 'Policiais que atendem as chamadas na central';
COMMENT ON TABLE TB_CHM_CHAMADA IS 'Chamadas recebidas pela delegacia';
COMMENT ON COLUMN TB_CHM_ATENDENTE.ID_POLICIAL IS 'Policial do modulo 01 (TB_PLC_POLICIAL)';
